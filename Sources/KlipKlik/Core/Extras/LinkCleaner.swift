import AppKit

/// Rewrites a freshly copied link without its trackers, before history sees it.
///
/// Runs inside `ClipboardMonitor`'s existing tick rather than on a timer of its
/// own: the monitor has already noticed the change, so a second poll would only
/// read the same counter twice.
///
/// Conservative about what it touches. Only a copy that is *nothing but* one
/// link is rewritten. Anything with HTML, RTF, an image or a file next to it is
/// left alone, because writing the pasteboard replaces every flavour on it and
/// the rest of that copy would be lost.
final class LinkCleaner {
    /// The link as it was copied, kept so the clean can be undone.
    private(set) var lastOriginal: String?
    /// Pasteboard generation produced by the last rewrite. While the
    /// pasteboard still sits at it, the cleaned link is what is on it.
    private(set) var lastCleanedChangeCount: Int?
    /// Generation written by "Restore Original Link", which must not be
    /// cleaned straight back.
    private var restoredChangeCount: Int?

    /// Types a bare link copy carries. Anything else on the pasteboard means
    /// there is more to the copy than the link.
    private static let linkOnlyTypes: Set<String> = [
        NSPasteboard.PasteboardType.string.rawValue,
        NSPasteboard.PasteboardType.URL.rawValue,
        "public.url-name",
        "public.utf16-external-plain-text",
        "NSStringPboardType",
        "NeXT plain ascii pasteboard type",
        "com.apple.pasteboard.source",
        "org.chromium.source-url",
        "org.chromium.internal.source-rfh-token",
        "com.apple.is-remote-clipboard"
    ]

    private static let concealedMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    /// True while the pasteboard still holds a link this cleaned.
    var canRestore: Bool {
        lastOriginal != nil && lastCleanedChangeCount == NSPasteboard.general.changeCount
    }

    /// Cleans the pasteboard in place if it holds one tracked link.
    ///
    /// - Returns: the pasteboard's change count after the rewrite, or nil when
    ///   nothing was written.
    func rewriteIfTracked(_ pasteboard: NSPasteboard) -> Int? {
        let changeCount = pasteboard.changeCount
        if restoredChangeCount == changeCount { return nil }

        guard let items = pasteboard.pasteboardItems, items.count == 1 else { return nil }
        let types = Set(items[0].types.map(\.rawValue))
        guard types.isDisjoint(with: Self.concealedMarkers),
              types.isSubset(of: Self.linkOnlyTypes)
        else { return nil }

        guard let text = pasteboard.string(forType: .string)
                ?? pasteboard.string(forType: .URL),
              let cleaned = URLCleaner.clean(text)
        else { return nil }

        // Another copy may have landed while this was reading.
        guard pasteboard.changeCount == changeCount else { return nil }

        pasteboard.clearContents()
        pasteboard.setString(cleaned.url, forType: .string)
        if types.contains(NSPasteboard.PasteboardType.URL.rawValue) {
            pasteboard.setString(cleaned.url, forType: .URL)
        }

        lastOriginal = text.trimmingCharacters(in: .whitespacesAndNewlines)
        lastCleanedChangeCount = pasteboard.changeCount
        log("cleaned \(cleaned.removed.joined(separator: ","))")
        return pasteboard.changeCount
    }

    /// Puts the link back exactly as it was copied. The write is left for the
    /// monitor to record, so the original shows up in history too.
    func restoreOriginal() {
        guard canRestore, let original = lastOriginal else { return }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(original, forType: .string)
        restoredChangeCount = pasteboard.changeCount
        lastOriginal = nil
        lastCleanedChangeCount = nil
    }

    private func log(_ message: String) {
        guard ProcessInfo.processInfo.environment["KLIPKLIK_DEBUG"] != nil else { return }
        FileHandle.standardError.write("linkclean: \(message)\n".data(using: .utf8)!)
    }
}
